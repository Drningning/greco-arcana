#!/usr/bin/env python3
"""
Navigation update v2 for the hand-written Greco Arcana pages (re-runnable).

For every page that uses the standard site menu (<ul class="nav-links" id="navLinks">):
  * replaces the whole menu with the v2 menu:
      The Practitioner · Offerings · Investigations (dropdown) · Study the Mysteries (dropdown)
    "The Library" is renamed "Investigations"; the standalone Silver Temple item moves into
    the new "Study the Mysteries" dropdown beside The Solitary Study
  * switches /assets/css/nav-v1.css to /assets/css/nav-v2.css
  * adds /assets/js/nav-v2.js (keyboard and screen-reader support for the dropdowns)
  * adds "The Solitary Study" to the footer's Practice column
Leaves the logo, the call-to-action button, page content and main.css untouched.
Pages generated by build_archives.py and build_study.py get the same menu from those scripts.
The Silver Temple pages use their own navigation and are skipped.
Safe to run twice: pages already updated are left as they are.
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARK = "<!-- nav:v2 -->"


def menu(path):
    home = path == "/"
    a = (lambda frag: frag) if home else (lambda frag: "/" + frag)
    offerings_active = path.startswith("/services/")
    inv_active = path.startswith(("/new-jersey/", "/lectures/", "/occult-archives/"))
    study_active = path.startswith(("/solitary-study/", "/silver-temple/"))
    cur = lambda p: ' aria-current="page"' if path == p else ""
    return f'''<ul class="nav-links" id="navLinks">{MARK}
      <li><a href="{a('#about')}">The Practitioner</a></li>
      <li{' class="is-active"' if offerings_active else ''}><a href="{a('#services') if home else '/services/'}"{cur('/services/')}>Offerings</a></li>
      <li class="nav-has-menu{' is-active' if inv_active else ''}"><a href="/occult-archives/">Investigations</a>
        <ul class="nav-submenu">
          <li><a href="/occult-archives/"{cur('/occult-archives/')}>The Occult Archives<span class="nav-sub-note">Chronicles &amp; Objects of Power</span></a></li>
          <li><a href="/new-jersey/"{cur('/new-jersey/')}>Hidden New Jersey<span class="nav-sub-note">Folklore of the towns I serve</span></a></li>
          <li><a href="/lectures/"{cur('/lectures/')}>Lectures<span class="nav-sub-note">The recorded corpus</span></a></li>
        </ul>
      </li>
      <li class="nav-has-menu{' is-active' if study_active else ''}"><a href="/solitary-study/">Study the Mysteries</a>
        <ul class="nav-submenu">
          <li><a href="/silver-temple/">The Silver Temple<span class="nav-sub-note">Directed esoteric study in a living mystery tradition</span></a></li>
          <li><a href="/solitary-study/"{cur('/solitary-study/')}>The Solitary Study<span class="nav-sub-note">A recommended syllabus for learning the Western esoteric tradition through the writers themselves</span></a></li>
        </ul>
      </li>
      <li class="nav-mobile-only"><a href="{a('#contact')}">Inquire</a></li>
    </ul>'''


def url_for(rel):
    rel = rel.replace(os.sep, "/")
    if rel == "index.html":
        return "/"
    if rel.endswith("/index.html"):
        return "/" + rel[: -len("index.html")]
    return "/" + rel


def replace_menu(s, new):
    """Replace the nav-links <ul> including any nested submenus."""
    start = s.find('<ul class="nav-links" id="navLinks">')
    if start < 0:
        return s, 0
    depth, i = 0, start
    tag = re.compile(r"<(/?)ul\b[^>]*>")
    for m in tag.finditer(s, start):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return s[:start] + new + s[m.end():], 1
    return s, 0


def main():
    changed, skipped = [], []
    for dirpath, dirnames, files in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in (".git", "node_modules", "occult-archives", "solitary-study", "silver-temple", "scripts", "assets")]
        for fn in files:
            if not fn.endswith(".html"):
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, ROOT)
            with open(full, encoding="utf-8") as f:
                s = f.read()
            if MARK in s or 'id="navLinks"' not in s:
                skipped.append(rel)
                continue
            s2, n = replace_menu(s, menu(url_for(rel)))
            if n != 1:
                skipped.append(rel)
                continue
            if "nav-v1.css" in s2:
                s2 = s2.replace("/assets/css/nav-v1.css", "/assets/css/nav-v2.css")
            elif "nav-v2.css" not in s2:
                s2 = s2.replace('<link rel="stylesheet" href="/assets/css/main.css">',
                                '<link rel="stylesheet" href="/assets/css/main.css">\n<link rel="stylesheet" href="/assets/css/nav-v2.css">', 1)
            if "/assets/js/nav-v2.js" not in s2:
                s2 = s2.replace("</body>", '<script src="/assets/js/nav-v2.js" defer></script>\n</body>', 1)
            footer = s2.split("<footer", 1)
            if len(footer) == 2 and "/solitary-study/" not in footer[1]:
                footer[1] = re.sub(r'(<h5>Practice</h5>\s*<ul>.*?)(\s*</ul>)',
                                   lambda m: m.group(1) + '\n          <li><a href="/solitary-study/">The Solitary Study</a></li>' + m.group(2),
                                   footer[1], count=1, flags=re.S)
                s2 = "<footer".join(footer)
            with open(full, "w", encoding="utf-8") as f:
                f.write(s2)
            changed.append(rel)
    print(f"Navigation v2 applied to {len(changed)} pages; {len(skipped)} skipped.")
    for c in sorted(skipped):
        print("  skipped", c)


if __name__ == "__main__":
    main()
